const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const Drafts=vm.runInNewContext(fs.readFileSync('assets/studio/client/web/product-drafts.js','utf8')+'\nProductDrafts;');
const drafts=new Drafts();
const job={id:'one',facts:'',product_facts:''};
assert.equal(drafts.value(job,'same'),'');
job.product_facts='自动提取：茶香香薰';
assert.equal(drafts.value(job,'same'),'自动提取：茶香香薰');
assert.equal(drafts.value(job,'switch'),'');
drafts.edit(job,'switch','新商品：咖啡杯');
drafts.edit(job,'same','人工修改的卖点');
job.product_facts='重新提取：花香香薰';
assert.equal(drafts.value(job,'same'),'人工修改的卖点');
assert.equal(drafts.value(job,'switch'),'新商品：咖啡杯');
assert.equal(drafts.restore(job),'重新提取：花香香薰');
const another={id:'two',facts:'另一个商品'};
assert.equal(drafts.value(another,'same'),'另一个商品');
assert.equal(drafts.value(another,'switch'),'');
assert.equal(drafts.value(job,'switch'),'新商品：咖啡杯');
drafts.edit(job,'same','');
job.product_facts='提取更新';
assert.equal(drafts.value(job,'same'),'');
console.log('Product autofill, manual edit preservation, mode and job isolation: passed');
const imported=new Drafts(),withMaterial={id:'imported',product_facts:'参考香薰',material_drafts:{switch:{active:true,text:'目标杯子'},same:{active:false,text:'已停用资料'}}};
assert.equal(imported.value(withMaterial,'switch'),'目标杯子');assert.equal(imported.value(withMaterial,'same'),'参考香薰');
const jobForLibrary={id:'x',title:'原香薰参考',source:'https://example.com/original',product_profile:{product:{value:'原香薰'},needs_confirmation:[{value:'原商品待核对'}]},material_drafts:{switch:{active:true,kind:'images',source_id:'own-import',profile:{product:{value:'目标杯子'},needs_confirmation:[{value:'目标价格待核对'}]}}}};
const candidate=Drafts.libraryCandidate(jobForLibrary,'switch','商品：目标杯子\n卖点：\n配有杯盖');
assert.equal(candidate.name,'目标杯子');assert.equal(candidate.pending,'目标价格待核对');assert.ok(!candidate.source.includes('example.com'));
delete jobForLibrary.material_drafts.switch;
assert.equal(Drafts.libraryCandidate(jobForLibrary,'switch','商品：手动目标杯子\n配有杯盖').pending,'');
