const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const Drafts=vm.runInNewContext(fs.readFileSync('assets/studio/client/web/narration-drafts.js','utf8')+'\nNarrationDrafts;');
const storage=new Map(),adapter={getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)};
const model=new Drafts(adapter);
const batch={id:'batch-A',variants:[{segments:[{text:'开场。'},{text:'卖点。'}]},{segments:[{text:'第二条。'}]}]};
const job={id:'project-A',batches:[batch]},other={id:'project-B',batches:[batch]};
assert.equal(model.batch(job).id,batch.id);
let rows=model.rows(job,batch);assert.equal(rows[0].text,'开场。\n\n卖点。');
rows[0].text='手动修改。';rows[1].selected=false;rows[0].collapsed=true;model.save(job,batch,rows);
assert.equal(model.rows(other,batch)[0].text,'开场。\n\n卖点。');
const reopened=new Drafts(adapter);assert.equal(reopened.rows(job,batch)[0].text,'手动修改。');assert.equal(reopened.rows(job,batch)[1].selected,false);
assert.equal(reopened.rows(job,batch)[0].collapsed,true);assert.equal(model.rows(other,batch)[0].collapsed,false);
batch.variants.push({segments:[{text:'生成中新增。'}]});
assert.equal(model.rows(job,batch)[0].text,'手动修改。');assert.equal(model.rows(job,batch)[2].selected,true);
model.projects.get(job.id).view='structure';job.batches.push({id:'batch-B',variants:[{segments:[{text:'新批次。'}]}]});
assert.equal(model.batch(job).id,'batch-B');assert.equal(model.projects.get(job.id).view,'summary');
model.projects.get(job.id).batch='batch-A';assert.equal(model.batch(job).id,'batch-A');assert.equal(model.rows(job,batch)[1].selected,false);
batch.variants[0].segments[0].text='生成原稿已改变。';assert.equal(model.rows(job,batch)[0].text,'生成原稿已改变。\n\n卖点。');
const broken=new Drafts({getItem:()=>'{broken',setItem:()=>{throw Error('quota');}});
assert.equal(broken.rows(job,batch).length,3);assert.equal(broken.save(job,batch,[]),false);
console.log('Narration drafts: project and batch isolation, persistence, streaming and source changes passed.');
const fileBatch={id:'file-batch',variants:[{segments:[{id:1,role:'钩子',text:'生成原稿'}],manuscript:{revision:3,text:'文件中的成稿',segments:[{id:1,role:'钩子',text:'文件中的成稿'}]}}]};
const fileJob={id:'file-job',batches:[fileBatch]},cleanBrowser=new Drafts(null);
const durable=cleanBrowser.rows(fileJob,fileBatch)[0];assert.equal(durable.text,'文件中的成稿');assert.equal(durable.revision,3);
durable.text='本窗口尚未保存';durable.dirty=true;
fileBatch.variants[0].manuscript={revision:4,text:'另一窗口已保存',segments:null};
assert.equal(cleanBrowser.rows(fileJob,fileBatch)[0].text,'本窗口尚未保存','Polling must preserve unsaved edits for conflict resolution');
durable.text='另一窗口已保存';
assert.equal(cleanBrowser.rows(fileJob,fileBatch)[0].revision,4);assert.equal(durable.dirty,false,'A save completed before reload must not be resubmitted');
console.log('File-backed manuscripts: cache-free load and concurrent-window edit preservation passed.');
