const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const Drafts=vm.runInNewContext(fs.readFileSync('assets/studio/client/web/reference-drafts.js','utf8')+'\nReferenceDrafts;');
const drafts=new Drafts();
const video={id:'video',kind:'upload',title:'A.mp4',source:'',facts:'A备注',auto_ai:false};
const link={id:'link',kind:'link',title:'B',source:'https://v.douyin.com/B/',facts:'B备注',auto_ai:true,link_provider:'tikhub'};
const file={name:'pending-A.mp4'};
drafts.save(video,{file,fileName:file.name,facts:'A尚未提交的备注'});
assert.equal(drafts.get(link).mode,'link');assert.equal(drafts.get(link).file,null);
assert.equal(drafts.get(link).fileName,'');assert.equal(drafts.get(link).link,link.source);
assert.equal(drafts.get(link).facts,'B备注');assert.equal(drafts.get(link).provider,'tikhub');
assert.equal(drafts.get(video).file,file);assert.equal(drafts.get(video).facts,'A尚未提交的备注');
assert.equal(drafts.get(video).autoAI,false);assert.equal(drafts.get(video).link,'');
drafts.save(null,{facts:'新建未提交',file:{name:'new.mp4'}});
assert.equal(drafts.get(link).facts,'B备注');drafts.resetNew();
assert.equal(drafts.get(null).facts,'');assert.equal(drafts.get(null).file,null);
drafts.setDefault('tikhub');drafts.resetNew();
assert.equal(drafts.get(null).provider,'tikhub');assert.equal(drafts.get(video).provider,'local');
assert.equal(drafts.get(link).provider,'tikhub');
console.log('Reference file/link/facts/options isolation and new-reference reset: passed');
const script={id:'script',kind:'script',title:'我的脚本.docx',raw:'开场。\n\n卖点。',script_file:'script.docx'};
assert.equal(drafts.get(script).mode,'script');assert.equal(drafts.get(script).scriptText,script.raw);
drafts.save(script,{scriptText:'未提交的新脚本',scriptFiles:[{id:'pending',name:'new.docx',file:{name:'new.docx'}}]});
assert.equal(drafts.get(video).scriptText,'');assert.equal(drafts.get(link).scriptFiles.length,0);
assert.equal(drafts.get(script).scriptText,'未提交的新脚本');assert.equal(drafts.get(script).scriptFiles[0].name,'new.docx');
drafts.removeScriptDocument('pending');assert.equal(drafts.get(script).scriptFiles.length,0);
drafts.save(null,{link:'视频分区草稿',facts:'视频商品'});drafts.setSpace('script');
assert.equal(drafts.get(null).mode,'script');assert.equal(drafts.get(null).link,'');
drafts.save(null,{scriptText:'脚本分区草稿',facts:'脚本商品'});drafts.setSpace('video');
assert.equal(drafts.get(null).link,'视频分区草稿');assert.equal(drafts.get(null).facts,'视频商品');
drafts.resetNew();drafts.setSpace('script');assert.equal(drafts.get(null).scriptText,'脚本分区草稿');assert.equal(drafts.get(null).facts,'脚本商品');
